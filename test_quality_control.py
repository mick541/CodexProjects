from quality_control import (
    format_quality_report,
    run_quality_control,
)


title = "Как проверить факты в статье перед публикацией"

text = """
Перед публикацией статьи редактору важно проверить ключевые утверждения,
цифры, даты и ссылки на источники. Сначала нужно выделить отдельные
проверяемые утверждения, а затем определить, какие из них требуют
подтверждения.

Для каждого важного факта желательно найти первичный источник: официальный
документ, исследование, статистику или прямое заявление организации.
Вторичные публикации можно использовать для контекста, но их не всегда
достаточно для подтверждения спорных деталей.

Также следует проверить, не изменился ли факт со временем. Особенно это
важно для цен, законов, правил платформ, статистики и технических
характеристик. Если подтверждение найти не удалось, формулировку лучше
смягчить или явно указать степень неопределённости.

Финальная проверка должна включать заголовок, подзаголовки, даты, числа,
имена собственные и ссылки. Это помогает снизить риск фактических ошибок
до публикации материала.
"""


result = run_quality_control(
    title=title,
    text=text,
    primary_query="проверка фактов",
    secondary_queries=[
        "фактчекинг статьи",
        "проверка информации",
        "источники",
    ],
    related_topics=[
        "редактура",
        "публикация",
        "проверка источников",
    ],
    claims=[
        "Факты в статье нужно проверять перед публикацией.",
        "Первичные источники полезны для подтверждения важных утверждений.",
    ],
)


print(format_quality_report(result))